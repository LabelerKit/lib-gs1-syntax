"""Turn gs1-syntax-engine's code-list bitfields into Rust tables.

Each list is stored there as an array of uint64 words, most significant bit
first, where set bit n means "n is an assigned code". The numeric lists index
by the code itself; the alpha-2 list indexes by a base-26 pair. We decode both
into plain sorted arrays, which are easier to read in a diff and cheap enough
to binary-search.
"""

import os
import re
import sys
import textwrap

sys.dont_write_bytecode = True  # this directory is ours, but keep it clean
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import provenance  # noqa: E402

SRC, OUT = sys.argv[1], sys.argv[2]

BIN = re.compile(r'0b([01]{64})')
STRINGS = re.compile(r'"([A-Z0-9]{1,4})"')


def bits(path, name):
    """Every set bit index in the named array's hex fallback."""
    body = open(f'{SRC}/lint_{path}.c', encoding='utf-8').read()
    start = body.index(f'static const uint64_t {name}[]')
    # Read the binary literals rather than the hex fallback: the fallback's
    # own comment contains a '};' that would end the block early, and the
    # binary form is the one GS1 annotates with the codes it stands for.
    end = body.index('#else', start)
    words = [int(b, 2) for b in BIN.findall(body[start:end])]
    out = []
    for i, w in enumerate(words):
        for b in range(64):
            if w & (1 << (63 - b)):
                out.append(i * 64 + b)
    return out


def alpha2(n):
    """The alpha-2 code a bit index stands for: 26 letters per position."""
    return chr(ord('A') + n // 26) + chr(ord('A') + n % 26)


countries = bits('iso3166', 'iso3166')
currencies = bits('iso4217', 'iso4217')
alpha = [alpha2(n) for n in bits('iso3166alpha2', 'iso3166alpha2')]

pkg_body = open(f'{SRC}/lint_packagetype.c', encoding='utf-8').read()
pkg_start = pkg_body.index('static const char packagetypes[][4]')
packages = STRINGS.findall(pkg_body[pkg_start:pkg_body.index('};', pkg_start)])

assert countries == sorted(countries) and len(set(countries)) == len(countries)
assert alpha == sorted(alpha)
assert packages == sorted(packages), 'the C table is binary-searched, so sorted'


def wrap(items, per_line, indent='    '):
    lines = []
    for i in range(0, len(items), per_line):
        lines.append(indent + ' '.join(f'{x},' for x in items[i:i + per_line]))
    return '\n'.join(lines)


credit = provenance.stamp(SRC, [f'{SRC}/lint_{n}.c' for n in (
    'iso3166', 'iso3166alpha2', 'iso4217', 'packagetype')])

wrapped = '\n//! '.join(textwrap.wrap('Derived from ' + credit, 77 - 4))

with open(OUT, 'w', encoding='utf-8') as f:
    f.write(f'''//! The published code lists the dictionary's linters refer to.
//!
//! Generated by `crates/gs1-syntax-gen/code-lists.py` from the tables in GS1's
//! own [gs1-syntax-engine](https://github.com/gs1/gs1-syntax-engine), where
//! they are kept as bitfields; here they are sorted arrays, which read better
//! in a diff and binary-search cheaply enough. Do not edit by hand.
//!
//! {wrapped}
//!
//! Each list is a snapshot of a standard that is revised from time to time.
//! That is the trade for checking membership at all: a code assigned after
//! this snapshot is rejected until the tables are regenerated, which is the
//! failure a reviewer can see rather than the one they cannot.

/// ISO 3166-1 numeric country codes, assigned as of the snapshot.
pub const COUNTRIES: &[u16] = &[
''')
    f.write(wrap(countries, 16) + '\n];\n\n')
    f.write('/// ISO 3166-1 alpha-2 country codes, assigned as of the snapshot.\n')
    f.write('pub const COUNTRIES_ALPHA2: &[&str] = &[\n')
    f.write(wrap([f'"{a}"' for a in alpha], 12) + '\n];\n\n')
    f.write('/// ISO 4217 numeric currency codes, assigned as of the snapshot.\n')
    f.write('pub const CURRENCIES: &[u16] = &[\n')
    f.write(wrap(currencies, 16) + '\n];\n\n')
    f.write('''/// UN/ECE Recommendation 21 freight unit type codes, plus the additions GS1
/// maintains on Navigator, which §3.8.19 says are equally valid.
pub const PACKAGE_TYPES: &[&str] = &[
''')
    f.write(wrap([f'"{p}"' for p in packages], 12) + '\n];\n')

print(f'{len(countries)} countries, {len(alpha)} alpha-2, '
      f'{len(currencies)} currencies, {len(packages)} package types')
print('sample:', countries[:6], alpha[:4], currencies[:4], packages[:4])
